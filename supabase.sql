create table if not exists public.links (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]{3,24}$'),
  original_url text not null,
  clicks bigint not null default 0,
  created_at timestamptz not null default now(),
  last_clicked_at timestamptz
);

alter table public.links enable row level security;

-- The browser never talks directly to this table. Vercel API functions use
-- SUPABASE_SERVICE_ROLE_KEY server-side; never put that key in public files.
-- No anon policies are intentionally created.
create index if not exists links_created_at_idx on public.links (created_at desc);
create index if not exists links_slug_idx on public.links (slug);